export function resolveLanguage(preference, languages = []) {
  if (preference === 'zh' || preference === 'en') return preference;
  return /^zh(?:-|$)/i.test(languages[0] || 'en') ? 'zh' : 'en';
}
export function resolveTheme(preference, dark) {
  return preference === 'light' || preference === 'dark' ? preference : (dark ? 'dark' : 'light');
}
export function t(key, values = {}, language = typeof document === 'undefined' ? 'zh' : document.documentElement.lang) {
  const template = language.startsWith('zh') ? key : (messages[key] || key);
  return template.replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? `{${k}}`));
}
export function setMessage(element, key, values = {}) {
  element.dataset.messageKey=key;
  element.dataset.messageValues=JSON.stringify(values);
  element.textContent=t(key,values);
}
const reverse = new Map(Object.entries(messages).map(([zh,en]) => [en,zh]));
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
export function translateStatic(root = document.body) {
  root.querySelectorAll('[data-message-key]').forEach(element=>{
    element.textContent=t(element.dataset.messageKey,JSON.parse(element.dataset.messageValues || '{}'));
  });
  const normalize = value => value.replace(/\s+/g,' ').trim();
  const translate = (value, state) => {
    const clean = normalize(value);
    const key = state?.last === value ? state.key : (messages[clean] ? clean : reverse.get(clean));
    const result = key ? value.replace(value.trim(), t(key)) : value;
    return {key, last:result};
  };
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement.closest('script,style,[data-source-text]')) {
      const result=translate(node.nodeValue,originalText.get(node));
      node.nodeValue=result.last; originalText.set(node,result);
    }
  }
  root.querySelectorAll('[aria-label],[placeholder],[title]').forEach(el => {
    const state=originalAttributes.get(el) || {};
    for (const attr of ['aria-label','placeholder','title']) if (el.hasAttribute(attr)) {
      state[attr]=translate(el.getAttribute(attr),state[attr]); el.setAttribute(attr,state[attr].last);
    }
    originalAttributes.set(el,state);
  });
  if (document.querySelector('#about-content')) document.title = t('关于 · Bing 每日壁纸归档');
}
